"""Execution validation: approval binding, fixed local commands, independent
acceptance checks.

Approval is bound to the *exact* candidate file hashes, the requirement text
and the plan revision in force when it was granted — any change to any of
those three invalidates it. Only fixed, tool-owned commands are ever executed;
no command is ever taken from model output. The timeout and bounded output
capture here protect *this tool's* bookkeeping only: once a command starts, it
still runs with the current user's full file and network access. That is not
a security boundary and must never be documented as one.
"""
from __future__ import annotations

import subprocess
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Dict, List, Optional, Sequence

DEFAULT_TIMEOUT_SECONDS = 60
DEFAULT_MAX_OUTPUT_BYTES = 200_000


class ValidationError(RuntimeError):
    """Raised when validation configuration or an execution request is invalid."""


class ApprovalMismatchError(ValidationError):
    """Raised when execution approval is missing or does not match the exact
    candidate hashes, requirement or plan revision presented for execution."""


@dataclass(frozen=True)
class ExecutionApproval:
    """A manual approval bound to one exact candidate state."""

    candidate_hashes: Dict[str, str]
    requirement_hash: str
    plan_revision: int

    def matches(self, candidate_hashes: Dict[str, str], requirement_hash: str, plan_revision: int) -> bool:
        return (
            self.candidate_hashes == candidate_hashes
            and self.requirement_hash == requirement_hash
            and self.plan_revision == plan_revision
        )


def create_execution_approval(candidate_hashes: Dict[str, str], requirement_hash: str,
                               plan_revision: int) -> ExecutionApproval:
    """Create an approval bound to the exact candidate hashes, requirement and plan revision."""
    return ExecutionApproval(dict(candidate_hashes), requirement_hash, plan_revision)


def verify_execution_approval(approval: Optional[ExecutionApproval], candidate_hashes: Dict[str, str],
                               requirement_hash: str, plan_revision: int) -> None:
    """Raise unless a matching execution approval exists for this exact candidate state.

    Raises:
        ApprovalMismatchError: no approval was granted, or the candidate hashes,
            requirement or plan revision no longer match what was approved.
    """
    if approval is None:
        raise ApprovalMismatchError("execution has not been approved")
    if not approval.matches(candidate_hashes, requirement_hash, plan_revision):
        raise ApprovalMismatchError(
            "execution approval does not match the current candidate hashes, "
            "requirement or plan revision; a fresh approval is required"
        )


@dataclass
class CommandResult:
    """The bounded outcome of one fixed, tool-owned local command."""

    command: Sequence[str]
    exit_code: Optional[int]
    stdout: str
    stderr: str
    timed_out: bool
    duration_seconds: float


def run_fixed_command(command: Sequence[str], cwd: Path, *,
                       timeout_seconds: int = DEFAULT_TIMEOUT_SECONDS,
                       max_output_bytes: int = DEFAULT_MAX_OUTPUT_BYTES,
                       runner: Callable[..., "subprocess.CompletedProcess"] = subprocess.run) -> CommandResult:
    """Run one fixed, tool-owned command with a process timeout and bounded output capture.

    ``command`` must come from this tool's own fixed command list — never from
    model output. ``runner`` is injected so tests never need a real subprocess.
    """
    started = time.monotonic()
    try:
        completed = runner(
            list(command), cwd=str(cwd), capture_output=True, text=True, timeout=timeout_seconds,
        )
    except subprocess.TimeoutExpired as exc:
        duration = time.monotonic() - started
        raw_stdout = exc.stdout or ""
        raw_stderr = exc.stderr or ""
        return CommandResult(
            command=tuple(command), exit_code=None,
            stdout=raw_stdout[:max_output_bytes], stderr=raw_stderr[:max_output_bytes],
            timed_out=True, duration_seconds=duration,
        )
    duration = time.monotonic() - started
    return CommandResult(
        command=tuple(command), exit_code=completed.returncode,
        stdout=(completed.stdout or "")[:max_output_bytes], stderr=(completed.stderr or "")[:max_output_bytes],
        timed_out=False, duration_seconds=duration,
    )


@dataclass
class AcceptanceCheck:
    """One independent, tool-owned behavior check — not generated by the model."""

    name: str
    check: Callable[[Path], bool]


@dataclass
class AcceptanceResult:
    name: str
    passed: bool
    detail: str = ""


def run_acceptance_checks(candidate_dir: Path, checks: Sequence[AcceptanceCheck]) -> List[AcceptanceResult]:
    """Run independent, tool-owned acceptance checks against the candidate.

    These checks are authored by this tool against the API acceptance criteria,
    not by the model, so a model-generated test suite that asserts away a bug
    cannot mask it from release evidence.
    """
    results: List[AcceptanceResult] = []
    for check in checks:
        try:
            passed = bool(check.check(candidate_dir))
            results.append(AcceptanceResult(name=check.name, passed=passed))
        except Exception as exc:  # noqa: BLE001 - a failing check is evidence, not a crash
            results.append(AcceptanceResult(name=check.name, passed=False, detail=str(exc)))
    return results
